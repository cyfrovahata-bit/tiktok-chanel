// Наголоси у власних назвах. Кожен рядок тут — назва, яку рушій уже прочитав
// у ролику неправильно; тест не дає їй загубитися вдруге. Особливо це
// стосується відмінків: тричі поспіль у словнику був називний, а в сценарії
// стояв орудний або родовий, і заміна мовчки не спрацьовувала.
import test from 'node:test';
import assert from 'node:assert/strict';
import { fixPronunciation, toSpeechCase } from '../src/tts.js';

// Сценарії приходять великими літерами, тож перевіряємо саме той шлях.
const say = (line) => fixPronunciation(toSpeechCase(line));

test('Скнилів: наголос на «и» в усіх формах', () => {
  assert.match(say('СКНИЛІВ'), /скни́лів/i);
  assert.match(say('НАД СКНИЛІВОМ'), /скни́лівом/i);
  assert.match(say('У СКНИЛОВІ'), /скни́лові/i);
  assert.match(say('СКНИЛІВСЬКОГО АЕРОДРОМУ'), /скни́лівського/i);
  assert.match(say('СКНИЛІВСЬКА ТРАГЕДІЯ'), /скни́лівська/i);
});

test("Зінов'євськ: орудний відмінок теж наголошений", () => {
  // Саме ця форма стояла в ролику про Кропивницький і читалася неправильно.
  assert.match(say('НАЗВАЛА ЙОГО ЗІНОВ’ЄВСЬКОМ'), /зіно́в'євськом/i);
  assert.match(say('ГРИГОРІЯ ЗІНОВ’ЄВА'), /григо́рія зіно́в'єва/i);
});

test('апостроф ловиться в усіх трьох накресленнях', () => {
  for (const apostrophe of ["'", '’', 'ʼ']) {
    assert.match(say(`ЗІНОВ${apostrophe}ЄВСЬК`), /зіно́в'євськ/i);
  }
});

test('назви міст із ролика про п’ять назв Кропивницького', () => {
  assert.match(say('НА БЕРЕГАХ ІНГУЛУ'), /інгу́лу/i);
  assert.match(say('МІСТОМ ЄЛИСАВЕТГРАДОМ'), /єлисаветгра́дом/i);
  assert.match(say('ФОРТЕЦЮ СВЯТОЇ ЄЛИЗАВЕТИ'), /єлизаве́ти/i);
  assert.match(say('З’ЯВИЛОСЯ КІРОВЕ'), /кі́рове/i);
  assert.match(say('ЗГОДОМ КІРОВОГРАД'), /кіровогра́д/i);
  assert.match(say('У КРОПИВНИЦЬКОМУ'), /кропивни́цькому/i);
  assert.match(say('УРОДЖЕНЦЯ ЖИТОМИРА'), /жито́мира/i);
});

test('«Кіров» не з’їдає початок слова «Кіровоград»', () => {
  const line = say('КІРОВОГРАДЩИНА');
  assert.match(line, /кіровогра́дщина/i);
  // Один наголос на слово, а не два.
  assert.equal((line.match(/́/g) || []).length, 1);
});

test('«опали» — іменник опа́ла, а не «о́пали»', () => {
  assert.match(say('ПІСЛЯ ЙОГО ОПАЛИ'), /опа́ли/i);
});

test('числівники другого десятка, написані словами', () => {
  // Через numbersToWords вони не проходять — там лише цифри.
  assert.match(say('ВІСІМНАДЦЯТОГО СТОЛІТТЯ'), /вісімна́дцятого/i);
  assert.match(say('ОДИНАДЦЯТОЇ ГОДИНИ'), /одина́дцятої/i);
  assert.match(say('СІМНАДЦЯТЬ РОКІВ'), /сімна́дцять/i);
});

test('число з цифр не дістає другого наголосу', () => {
  const line = say('18 СТОЛІТТЯ');
  assert.match(line, /вісімна́дцятого/i);
  assert.equal((line.match(/́/g) || []).length, 1);
});

test('за́мок — фортеця, а не замо́к на дверях', () => {
  assert.match(say('ОСТРОЗЬКИЙ ЗАМОК'), /за́мок/i);
  assert.match(say('У ЗАМКУ'), /за́мку/i);
  assert.match(say('НАД ЗАМКОМ'), /за́мком/i);
  assert.match(say('ДЕСЯТКИ ЗАМКІВ'), /за́мків/i);
});
