// Правка сюжету в мінідодатку переписує промт у колонці G. Тексти слайдів
// лежать там у двох місцях, і розійтися вони не мають.
import test from 'node:test';
import assert from 'node:assert/strict';
import { parseSlideLines, parseTheme, applySlideLines } from '../src/queue-prompt.js';

const PROMPT = `ЗАТВЕРДЖЕНИЙ СЦЕНАРІЙ. Твоє завдання — ЛИШЕ намалювати фото.

ТЕМА: ЯК ФОНТАН ЗИМУЄ НА ДНІ
КІЛЬКІСТЬ ФОТО: 3

ТЕКСТИ СЛАЙДІВ (рівно ці рядки й у цьому порядку йдуть у script.txt):
1. ЩО ЦЕ ЗА КОНСТРУКЦІЯ ПІД ВОДОЮ?
2. ВОСЕНИ ЇЇ ОПУСКАЮТЬ НА ДНО.
3. А ТИ БАЧИВ ЦЕЙ ФОНТАН?

ВІЗУАЛЬНИЙ КОНТЕКСТ:
МІСЦЕ: Вінниця

ЩО МАЄ БУТИ НА КОЖНОМУ КАДРІ:
1.jpg — Загадковий підводний кадр.
     (рядок: «ЩО ЦЕ ЗА КОНСТРУКЦІЯ ПІД ВОДОЮ?»)
2.jpg — Кран опускає платформу.
     (рядок: «ВОСЕНИ ЇЇ ОПУСКАЮТЬ НА ДНО.»)
3.jpg — Вечірня набережна.
     (рядок: «А ТИ БАЧИВ ЦЕЙ ФОНТАН?»)
`;

test('дістає тексти слайдів і тему', () => {
  assert.deepEqual(parseSlideLines(PROMPT), [
    'ЩО ЦЕ ЗА КОНСТРУКЦІЯ ПІД ВОДОЮ?',
    'ВОСЕНИ ЇЇ ОПУСКАЮТЬ НА ДНО.',
    'А ТИ БАЧИВ ЦЕЙ ФОНТАН?',
  ]);
  assert.equal(parseTheme(PROMPT), 'ЯК ФОНТАН ЗИМУЄ НА ДНІ');
});

test('замінює рядок В ОБОХ місцях промту', () => {
  const out = applySlideLines(PROMPT, [
    'ЩО ЦЕ ЗА КОНСТРУКЦІЯ ПІД ВОДОЮ?',
    'ПІЗНЬОЇ ОСЕНІ ЇЇ ОПУСКАЮТЬ НА ДНО.',
    'А ТИ БАЧИВ ЦЕЙ ФОНТАН?',
  ]);
  assert.equal(parseSlideLines(out)[1], 'ПІЗНЬОЇ ОСЕНІ ЇЇ ОПУСКАЮТЬ НА ДНО.');
  assert.match(out, /\(рядок: «ПІЗНЬОЇ ОСЕНІ ЇЇ ОПУСКАЮТЬ НА ДНО\.»\)/);
  assert.doesNotMatch(out, /ВОСЕНИ ЇЇ ОПУСКАЮТЬ/);
});

test('решта промту лишається недоторканою', () => {
  const out = applySlideLines(PROMPT, [
    'НОВИЙ ПЕРШИЙ РЯДОК?',
    'ВОСЕНИ ЇЇ ОПУСКАЮТЬ НА ДНО.',
    'А ТИ БАЧИВ ЦЕЙ ФОНТАН?',
  ]);
  assert.match(out, /КІЛЬКІСТЬ ФОТО: 3/);
  assert.match(out, /МІСЦЕ: Вінниця/);
  assert.match(out, /2\.jpg — Кран опускає платформу\./);
});

test('не дає змінити кількість слайдів', () => {
  assert.throws(() => applySlideLines(PROMPT, ['ЛИШЕ ОДИН РЯДОК.']), /Очікував 3/);
});

test('не приймає порожній рядок слайда', () => {
  assert.throws(
    () => applySlideLines(PROMPT, ['ОК.', '   ', 'ОК.']),
    /Порожній рядок/,
  );
});

test('промт без блоку слайдів не ламає розбір', () => {
  assert.deepEqual(parseSlideLines('просто текст'), []);
  assert.equal(parseTheme('просто текст'), '');
});
