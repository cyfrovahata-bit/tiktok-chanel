// Факти, чиї тексти вже стали темами (done/rejected/pending), виключаються —
// порівняння точне, бо саме цей текст іде в тему один в один.
export function remainingFacts(usedTitles) {
  const used = new Set(usedTitles);
  return FACTS_POOL.filter((fact) => !used.has(fact.text));
}

// Випадковий (не по черзі й не по категоріях) ще не використаний факт;
// null, якщо пул вичерпано — тоді generateTheme() повертається до GPT.
export function pickPoolFact(usedTitles) {
  const remaining = remainingFacts(usedTitles);
  if (remaining.length === 0) return null;
  return remaining[Math.floor(Math.random() * remaining.length)].text;
}
