// Короткі схвальні коментарі — «дякую», «цікаво», сердечко — відповідаються
// АВТОМАТИЧНО, без картки в Telegram. Їх найбільше, і саме вони з'їдали
// найбільше часу власника, хоч рішення там нема ніякого.
//
// Розпізнаємо їх правилами, а не моделлю, і це навмисно: правило видно очима,
// воно безкоштовне й дає той самий результат щоразу. Модель на «дякую, але у
// вас помилка в даті» могла б відповісти «дякую!» — а це вже публічна
// дурниця, яку ніхто не схвалював.
//
// Правило одне: відповідаємо самі ЛИШЕ там, де немає ані питання, ані
// заперечення, ані фактів. Найменший сумнів — коментар іде власникові.

// Емодзі, символи-модифікатори, розділові знаки. Те, що лишається після
// зняття цього всього, і є «текстом» коментаря.
const DECOR = /[\p{Extended_Pictographic}\p{Emoji_Component}\p{P}\p{S}\s]+/gu;

function bare(text) {
  return String(text || '').replace(DECOR, ' ').trim().toLowerCase();
}

// Слова подяки й схвалення. Тільки основи: далі порівнюємо за початком слова,
// тож «дякую», «дякуємо», «дяки» ловляться однією.
const PRAISE = [
  'дяк', 'спасиб', 'клас', 'супер', 'круто', 'кльов', 'гарн', 'чудов', 'файн',
  'цікав', 'пізнавальн', 'корисн', 'вау', 'ого', 'топ', 'молодц', 'молодец',
  'браво', 'респект', 'люкс', 'прекрасн', 'шикарн', 'неймовірн', 'вражає',
  'дізнав', 'дізнал',
];

// Похвала з кількох слів. Її шукаємо саме як фразу — по окремих словах вона
// не збереться.
const PRAISE_PHRASES = ['не знав', 'не знала', 'не знали', 'вперше чую', 'вперше чув'];

// Після «не» похвала перетворюється на свою протилежність. Виняток — оці:
// «не знав» і «не чув» якраз і означають, що ролик був корисний.
const NEGATION_OK = ['знав', 'знала', 'знали', 'чув', 'чула', 'чули', 'думав', 'думала'];

// Те, що миттєво знімає коментар з автовідповіді, хай яким коротким він був.
const STOP = [
  'але', 'проте', 'однак', 'хіба', 'чому', 'навіщо', 'звідки', 'коли', 'де саме',
  'помилк', 'невірн', 'неправд', 'брехн', 'фейк', 'не так', 'насправді',
  'джерел', 'підтверд', 'доведіть', 'пруф',
];

// Службові слова, які нічого не означають самі по собі, але природно стоять
// поруч із подякою: «дякую ЗА РОЛИК», «дуже цікаво».
const FILLER = new Set([
  'за', 'це', 'цей', 'ця', 'цього', 'того', 'такого', 'такий', 'така', 'таке',
  'дуже', 'так', 'ще', 'і', 'й', 'та', 'у', 'в', 'на',
  'про', 'вам', 'вас', 'ваш', 'ваші', 'вами', 'тобі', 'тебе', 'всім', 'усім',
  'все', 'усе', 'автор', 'автору', 'канал', 'каналу', 'ролик', 'ролику',
  'ролики', 'роликів', 'відео', 'контент', 'робота', 'роботу', 'хлопці',
  'дівчата', 'друзі', 'команда', 'вийшло', 'зроблено', 'подача',
]);

const MAX_WORDS = 5;

// Чи це той самий короткий схвальний коментар, на який можна відповісти самим.
export function isShortAppreciation(text) {
  const raw = String(text || '');
  if (!raw.trim()) return false;
  // Питання — це завжди до власника: там або факт, або суперечка.
  if (/[?？]/.test(raw)) return false;
  // Посилання й згадки — майже завжди спам або звернення до третьої особи.
  // Клас \w кирилицю не бачить, тож згадку описуємо через властивість «літера».
  if (/https?:\/\/|www\.|@[\p{L}\d._-]/iu.test(raw)) return false;
  // Числа й дати — розмова про факти, а не про враження.
  if (/\d/.test(raw)) return false;

  const words = bare(raw).split(/\s+/).filter(Boolean);

  // Сам лише емодзі чи розділові знаки — найпростіший випадок.
  if (!words.length) return true;

  if (words.length > MAX_WORDS) return false;
  const flat = words.join(' ');
  if (STOP.some((stop) => flat.includes(stop))) return false;

  // «не цікаво», «не сподобалось» — це не подяка, хоч слово всередині те саме.
  for (let i = 0; i < words.length - 1; i++) {
    if (words[i] !== 'не') continue;
    if (!NEGATION_OK.some((ok) => words[i + 1].startsWith(ok))) return false;
  }

  const isPraiseWord = (word) => PRAISE.some((root) => word.startsWith(root));
  // Порівнюємо ТІЛЬКИ початок слова: інакше «нецікаво» містить «цікав» і
  // проходить як похвала — рівно навпаки до сказаного.
  const hasPraise = PRAISE_PHRASES.some((phrase) => flat.includes(phrase))
    || words.some(isPraiseWord);
  if (!hasPraise) return false;

  // І головне: КОЖНЕ слово має бути або похвалою, або службовим. Питання часто
  // пишуть без знака питання — «цікаво а де це», — і за самим лише пошуком
  // похвали такий коментар отримав би у відповідь «дякуємо!». Незнайоме слово
  // означає, що в коментарі є ще щось, крім враження, і читати це має власник.
  return words.every((word) => FILLER.has(word) || isPraiseWord(word)
    || PRAISE_PHRASES.some((phrase) => phrase.split(' ').includes(word)));
}

