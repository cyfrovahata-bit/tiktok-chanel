export function parseCaption(answer) {
  return String(answer || '')
    .trim()
    .split('\n')[0]
    .replace(/^[«»"'“”\-–—•\s]+/, '')
    .replace(/[.!?…«»"'“”\s]+$/, '')
    .trim()
    .toUpperCase();
}

// Чи напис поганий. Повертає причину або '' — тоді все гаразд.
//
// items потрібні для головної перевірки: напис мусить бути про ВСЮ добірку.
// «ЗНАЙШЛИ МАГНІТОМ» під п'ятнадцятьма фактами обіцяє відео про одне місто —
// глядач відкриє його по цю обіцянку й піде, не знайшовши її.
export function captionWeakness(caption, { items = [] } = {}) {
  const text = String(caption || '').trim();
  if (!text) return 'порожній';
  if (/[?？]/.test(text)) return 'запитання';
  if (/\d/.test(text)) return 'число замість обіцянки';

  const words = text.split(/\s+/).filter(Boolean);
  if (words.length > CAPTION_MAX_WORDS) return `${words.length} слів замість ${CAPTION_MAX_WORDS}`;
  if (text.length > CAPTION_MAX_CHARS) return `${text.length} літер замість ${CAPTION_MAX_CHARS}`;

  // Слова, які є лише в назві одного факту, видають напис про нього одного.
  // Спільні для набору («фортеця» в половині назв) навпаки — те, що треба.
  const said = new Set(stems(text));
  const single = items.some((it, i) => {
    const others = new Set(items
      .filter((_, j) => j !== i)
      .flatMap((other) => stems(`${other.title || ''} ${other.theme || ''}`)));
    return stems(`${it.title || ''} ${it.theme || ''}`)
      .some((w) => !others.has(w) && said.has(w));
  });
  return single ? 'обіцяє один факт замість усієї добірки' : '';
}

// Запасний напис, коли модель не дала свого. Беремо зі значущих слів назви:
// «Серед кам'яних свідків» → «КАМ'ЯНИХ СВІДКІВ». Прийменники й займенники
// викидаємо — на обкладинці вони займають місце й нічого не обіцяють, а
// обрізана назва на кшталт «УКРАЇНА ЯКОЇ ТИ» виглядає як помилка.
const CAPTION_SKIP = new Set([
  'серед', 'через', 'після', 'перед', 'проти', 'понад', 'разом', 'зовсім',
  'який', 'яка', 'яке', 'які', 'якої', 'якого', 'якому', 'яких',
  'тобі', 'тебе', 'тільки', 'дуже', 'ще', 'вже', 'було', 'була', 'були',
  'свій', 'своя', 'своє', 'свої', 'його', 'їхні', 'цього', 'цьому',
]);

export function captionFromTitle(title) {
  // Апостроф — частина слова, а не розділовий знак: «кам'яних» без нього
  // розпадається на два огризки.
  const words = String(title || '')
    .replace(/[«»"“”.,!?;:]/g, ' ')
    .split(/\s+/)
    .filter(Boolean)
    // Короткі слова на обкладинці лише крадуть висоту в решти літер.
    .filter((w) => w.length >= 5 && !CAPTION_SKIP.has(w.toLowerCase()));

  const out = [];
  for (const word of words) {
    if (out.length >= 2) break;
    if ([...out, word].join(' ').length > CAPTION_MAX_CHARS) break;
    out.push(word);
  }
  return out.join(' ').toUpperCase();
}

