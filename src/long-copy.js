// Порівнюємо слова по п'ятилітерній основі: у хвості буде «фортець», у назві
// «фортеця» — точне порівняння такий збіг проґавить.
function stems(text) {
  return String(text || '')
    .toLowerCase()
    .replace(/[^\p{L}\d\s]+/gu, ' ')
    .split(/\s+/)
    .filter((w) => w.length >= 6)
    .map((w) => w.slice(0, 5));
}

const TAIL_CLICHES = [
  'здивує', 'здивують', 'вражаюч', 'неймовірн', 'дивовижн', 'ще більше',
  'варто побачити', 'не знав', 'не знали', 'не чув',
];

// Чи хвіст поганий. Повертає причину або '' — тоді все гаразд.
export function tailWeakness(tail, { items = [], title = '' } = {}) {
  // Знак питання шукаємо ДО обрізання: «а що всередині?» інакше втратило б
  // єдину свою прикмету й пройшло б як звичайний хвіст.
  if (String(tail || '').includes('?')) return 'запитання';
  const text = String(tail || '').trim().replace(/[.!?…]+$/, '');
  if (!text) return 'порожній';

  const words = text.split(/\s+/).filter(Boolean);
  if (words.length < TAIL_MIN_WORDS) return 'закороткий';
  if (words.length > TAIL_MAX_WORDS) return 'задовгий';

  const low = text.toLowerCase();
  const cliche = TAIL_CLICHES.find((c) => low.includes(c));
  if (cliche) return `кліше «${cliche}»`;

  // Назву добірки глядач бачить на заставці — повторювати її голосом зайве.
  const said = new Set(stems(text));
  if (stems(title).some((w) => said.has(w))) return 'повторює назву добірки';

  // Слова, які є лише в назві одного факту, видають анонс одного об'єкта —
  // а хвіст мусить називати спільне для всіх.
  const named = items.find((it, i) => {
    const others = new Set(items
      .filter((_, j) => j !== i)
      .flatMap((other) => stems(`${other.title || ''} ${other.theme || ''}`)));
    return stems(`${it.title || ''} ${it.theme || ''}`)
      .some((w) => !others.has(w) && said.has(w));
  });
  return named ? 'називає окремий факт, а не спільне' : '';
}

export function parseTail(answer) {
  return String(answer || '')
    .trim()
    .split('\n')[0]
    // Лапки й крапка можуть іти в будь-якому порядку («…».), тож чистимо
    // кожен край одним класом, а не двома проходами.
    .replace(/^[«»"'“”\-–—•\s]+/, '')
    .replace(/[.!?…«»"'“”\s]+$/, '')
    .trim();
}

