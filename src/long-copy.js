// другому ролику й пропускає повз вуха.
const HOOK_CLICHES = [
  'у цьому відео', 'в цьому відео', 'сьогодні ми', 'привіт', 'дізнайся',
  'дізнайтесь', 'дізнайтеся', 'розкриваємо', 'розкриємо', 'зануримо',
  'зануримось', 'занурся', 'поїхали', 'ви не повірите', 'шокує', 'підписуйся',
  // Порожня обіцянка замість другого факту — те, чим модель затикає друге
  // речення, коли їй нема чого сказати.
  'ще більше', 'ми покажемо', 'ми розповімо', 'покажемо ще', 'чекає на тебе',
  'вражаюч', 'неймовірн', 'дивовижн',
  // Заставка вже питає «Чи знав ти таку Україну?» — вступ це лише повторить.
  'чи знаєш ти', 'чи знав ти',
];

// Слова, спільні з назвами фактів, шукаємо по п'ятилітерній основі: у
// вступі буде «Хотинську», а в назві «Хотинська» — точне порівняння такий
// збіг проґавить.
function stems(text) {
  return String(text || '')
    .toLowerCase()
    .replace(/[^\p{L}\d\s]+/gu, ' ')
    .split(/\s+/)
    .filter((w) => w.length >= 6)
    .map((w) => w.slice(0, 5));
}

function firstSentence(text) {
  const m = /^[^.!?…]+/.exec(String(text || '').trim());
  return m ? m[0] : String(text || '');
}

// Чи вступ слабкий. Повертає причину (рядок) або '' — тоді все гаразд.
// Потрібно, щоб не ганяти в ефір «історія перетворює руїни на легенди»:
// модель зривається в таку абстракцію регулярно, і побачити це можна лише
// в готовому відео, за годину після монтажу.
//
// items мають бути в тому ж порядку, що й у відео: перший із них глядач
// побачить одразу після вступу, тож згадка про нього у вступі — це той самий
// об'єкт двічі поспіль.
export function hookWeakness(hook, items = []) {
  const text = String(hook || '').trim();
  if (!text) return 'порожній';
  const words = text.split(/\s+/).filter(Boolean);
  if (words.length > HOOK_WORD_LIMIT + 4) return 'задовгий';

  // Запитання у вступі — найгірший із можливих початків: на «чи знаєш ти,
  // що…» глядач подумки відповідає «ні» й гортає далі.
  if (text.includes('?')) return 'запитання замість твердження';

  const low = text.toLowerCase();
  const cliche = HOOK_CLICHES.find((c) => low.includes(c));
  if (cliche) return `кліше «${cliche}»`;

  // Слова, які є ЛИШЕ в першому факті: за ними видно, що вступ саме про нього,
  // а не про спільну для набору річ («фортеця» трапляється в половині назв).
  const rest = new Set(items.slice(1).flatMap((it) => stems(`${it.title || ''} ${it.theme || ''}`)));
  const onlyFirst = new Set(stems(items[0]?.title || items[0]?.theme || '').filter((w) => !rest.has(w)));
  const said = stems(text);
  if (said.some((w) => onlyFirst.has(w))) return 'вступ про перший факт — він піде одразу за ним';

  // Конкретика: у першому реченні має бути або число, або слово з назви
  // якогось факту. Інакше це вступ ні про що.
  const head = firstSentence(text);
  if (/\d/.test(head)) return '';
  const hit = stems(head).some((w) => rest.has(w));
  return hit ? '' : 'у першому реченні немає конкретики';
}

