const MODEL = process.env.OPENAI_SCENARIO_MODEL || process.env.OPENAI_FALLBACK_MODEL || 'gpt-4o-mini';

function apiKey() {
  const key = process.env.OPENAI_API_KEY;
  if (!key) throw new Error('Не задано OPENAI_API_KEY');
  return key;
}

// Витягує JSON з відповіді (модель могла обгорнути його в ```json ... ```).
function parseJsonLoose(text) {
  const cleaned = String(text).replace(/```json\s*|```/g, '').trim();
  const start = cleaned.indexOf('{');
  const end = cleaned.lastIndexOf('}');
  if (start < 0 || end < 0) throw new Error('OpenAI: у відповіді немає JSON');
  return JSON.parse(cleaned.slice(start, end + 1));
}

// Єдиний виклик моделі — звичайний chat/completions. Без інструментів, без
// веб-пошуку: одна відповідь на один запит, передбачувана вартість.
async function askModel(prompt) {
  const response = await fetch('https://api.openai.com/v1/chat/completions', {
    method: 'POST',
    headers: { authorization: `Bearer ${apiKey()}`, 'content-type': 'application/json' },
    body: JSON.stringify({
      model: MODEL,
      messages: [{ role: 'user', content: prompt }],
      response_format: { type: 'json_object' },
      temperature: 0.9,
    }),
  });
  if (!response.ok) throw new Error(`OpenAI: HTTP ${response.status} ${await response.text()}`);
  const data = await response.json();
  const content = data.choices?.[0]?.message?.content;
  if (!content) throw new Error('OpenAI: порожня відповідь');
  return parseJsonLoose(content);
}

