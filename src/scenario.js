function parseResult(raw, fallbackTheme = '') {
  const slides = (raw?.slides || [])
    .map((s) => ({ text: String(s?.text ?? '').trim(), image: String(s?.image ?? '').trim() }))
    .filter((s) => s.text);
  if (slides.length < 3) throw new Error('OpenAI повернув замало слайдів');
  return {
    theme: String(raw?.theme ?? fallbackTheme).trim(),
    wow: String(raw?.wow ?? '').trim(),
    // Розповідь абзацом — джерело, з якого нарізані слайди. Показуємо її
    // власнику: саме так найлегше почути, чи це історія, а не перелік.
    story: String(raw?.story ?? '').trim(),
    slides,
    sources: (raw?.sources || []).map(String).filter(Boolean).slice(0, 5),
    visual: raw?.visual && typeof raw.visual === 'object' ? raw.visual : null,
  };
}

