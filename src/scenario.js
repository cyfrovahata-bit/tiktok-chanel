// Промт для ChatGPT: затверджений сценарій + візуальний контекст. ChatGPT лише
// МАЛЮЄ за ним і пакує архів — тему не придумує і текстів не змінює.
export async function buildPromptText(draft, rowId = '') {
  const n = draft.slides.length;
  const v = draft.visual || {};
  const frames = draft.slides
    .map((s, i) => `${i + 1}.jpg — ${s.image || s.text}\n     (рядок: «${s.text}»)`)
    .join('\n');

  const context = [
    v.type && `ТИП ІСТОРІЇ: ${v.type}`,
    v.place && `МІСЦЕ: ${v.place}`,
    v.era && `ЧАС/ЕПОХА: ${v.era}`,
    v.mainObject && `ГОЛОВНИЙ ОБ'ЄКТ (має лишатися впізнаваним): ${v.mainObject}`,
    v.keyFeatures && `КЛЮЧОВІ ВІЗУАЛЬНІ ОЗНАКИ: ${v.keyFeatures}`,
    v.doNotInvent && `НЕ ВИГАДУВАТИ: ${v.doNotInvent}`,
  ].filter(Boolean).join('\n');

  // Посилання дала модель сценарію без веб-пошуку, тож це підказка, а не
  // доказ: ChatGPT має звірити їх сам, коли шукатиме референси.
  const sources = (draft.sources || []).length
    ? `\nОРІЄНТОВНІ ДЖЕРЕЛА (звір самостійно, посилання можуть бути неточні):\n${draft.sources.map((s) => `• ${s}`).join('\n')}\n`
    : '';

  return `ЗАТВЕРДЖЕНИЙ СЦЕНАРІЙ. Твоє завдання — ЛИШЕ намалювати фото й зібрати
архів. Тему НЕ придумуй, тексти слайдів НЕ змінюй, кількість не змінюй.

ТЕМА: ${draft.theme}
КІЛЬКІСТЬ ФОТО: ${n}

ТЕКСТИ СЛАЙДІВ (рівно ці рядки й у цьому порядку йдуть у script.txt):
${draft.slides.map((s, i) => `${i + 1}. ${s.text}`).join('\n')}

${context ? `ВІЗУАЛЬНИЙ КОНТЕКСТ:\n${context}\n` : ''}${sources}
ЩО МАЄ БУТИ НА КОЖНОМУ КАДРІ:
${frames}

═══════════════════════════════════════
ПОРЯДОК ДІЙ:
1. ПЕРЕВІР ФАКТИ веб-пошуком, перш ніж малювати. Головний факт і всі числа з
   текстів вище мають підтверджуватись щонайменше двома незалежними
   джерелами, одне з яких офіційне чи первинне (музей, університет, наукова
   публікація, держустанова, архів, UNESCO, Guinness, виробник). Заразом
   знайди реальні фото-референси об'єктів і малюй НАБЛИЖЕНО до справжнього
   вигляду, а не вигадану версію.
2. Згенеруй УСІ ${n} зображень 9:16 ОДРАЗУ, в одному стилі, реалістичні,
   кінематографічні, ЧИСТІ БЕЗ ТЕКСТУ — написи накладає застосунок.
   Верхні 40% кадру тримай візуально спокійними (туди ляже напис),
   головний об'єкт — нижче або по центру.
3. Зведена картинка — сітка з підписами 1…${n} (для перегляду оком).
4. АРХІВ .zip: рівно ${n} фото «1.jpg»…«${n}.jpg» (повна якість, порядок
   сценарію) + «script.txt» — тексти слайдів ПО ОДНОМУ РЯДКУ НА ФОТО
   (рядок 1 → 1.jpg, …), без нумерації, описів і розмітки. Інших файлів нема.
5. Завантаж ZIP у папку Google Drive.
6. ОНОВИ ЦЕЙ САМИЙ РЯДОК таблиці «Черга тем»${rowId ? ` (ID: ${rowId})` : ''} —
   НЕ створюй новий:
   • «Архів» — посилання на ZIP;
   • «Назва публікації» — заголовок для соцмереж;
   • «Опис для соцмереж» — гачок, коротке пояснення факту, запитання
     аудиторії, заклик підписатись і рівно 5 хештегів;
   • «Статус» — заміни NEW на DONE.
   Решту колонок НЕ чіпай і НЕ очищай — зокрема «Додаткові вказівки» (G),
   де лежить цей промт: він потрібен для перевірки.

ПЕРЕД ЗАВАНТАЖЕННЯМ ПЕРЕЛІЧИ ВГОЛОС І ЗВІР:
• скільки файлів-зображень в архіві — має бути рівно ${n};
• скільки рядків у script.txt — має бути рівно ${n};
• чи це тексти САМЕ цієї теми (звір перший і останній рядок зі списком вище).
Не збіглося — перезбери архів, а не завантажуй як є.

Якщо перевірка показала, що факт або число у сценарії помилкові чи їх не
вдалося підтвердити — НЕ малюй хибне і НЕ виправляй текст сам: постав статус
ERROR і коротко опиши проблему в «Примітці».`;
}

// Шаблон стилю каналу (лишено для сумісності зі старими шляхами).
export async function channelStyleTemplate(theme) {
  try {
    const t = await readFile(new URL('../prompt.template.txt', import.meta.url), 'utf8');
    return t.replaceAll('{{TEMA}}', theme);
  } catch {
    return '';
  }
}
