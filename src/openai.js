// OpenAI: генерація теми (воркфлоу themes) і текстів публікації (воркфлоу check).
import { pickPoolFact } from './facts-pool.js';

const MODEL = 'gpt-4o-mini';

async function chat(prompt, options = {}) {
  const key = process.env.OPENAI_API_KEY;
  if (!key) throw new Error('Не задано змінну середовища OPENAI_API_KEY');
  const response = await fetch('https://api.openai.com/v1/chat/completions', {
    method: 'POST',
    headers: {
      authorization: `Bearer ${key}`,
      'content-type': 'application/json',
    },
    body: JSON.stringify({
      model: MODEL,
      messages: [{ role: 'user', content: prompt }],
      ...options,
    }),
  });
  if (!response.ok) {
    throw new Error(`OpenAI: HTTP ${response.status} ${await response.text()}`);
  }
  const data = await response.json();
  const content = data.choices?.[0]?.message?.content;
  if (!content) throw new Error('OpenAI: порожня відповідь');
  return content.trim();
}

// Категорія обирається кодом (не GPT), щоб рotація була гарантована,
// а не залежала від того, чи «згадає» модель урізноманітнити самостійно.
// weight — відносна вага категорії в ротації (3 = утричі частіше за 1).
const THEME_CATEGORIES = [
  { name: 'тварини', weight: 1 },
  { name: 'космос', weight: 1 },
  { name: 'тіло людини', weight: 1 },
  { name: 'фізика чи хімія', weight: 1 },
  { name: 'історія', weight: 1 },
  { name: 'їжа', weight: 1 },
  { name: 'океан і морське життя', weight: 1 },
  { name: 'технології', weight: 1 },
  {
    name:
      'життєві факти — те, з чим людина реально стикається, бачить довкола ' +
      'себе або може сама перевірити вдома чи на роботі (побут, здоров\'я, ' +
      'їжа, техніка, звички) — не абстрактна наука, а щось із власного досвіду',
    weight: 3,
  },
  // Вага піднята: факти саме про Україну (винаходи, постаті, рекорди) явно
  // краще заходять українській аудиторії каналу, ніж нейтральна світова наука.
  { name: 'факти про Україну (природа, історія, культура, винаходи, рекорди)', weight: 2 },
];

function pickCategory() {
  const pool = THEME_CATEGORIES.flatMap((c) => Array(c.weight).fill(c.name));
  return pool[Math.floor(Math.random() * pool.length)];
}

export async function generateTheme(usedTitles) {
  // Спершу — випадковий (не по категоріях підряд) ще не використаний факт
  // із кураторського пулу; GPT не викликається, поки пул не вичерпано.
  const poolFact = pickPoolFact(usedTitles);
  if (poolFact) return poolFact;

  const category = pickCategory();
  const prompt = `Ти — контент-директор українського TikTok-каналу «Чи Ви Знали?».
Придумай ОДНУ нову тему для короткого факт-ролика з категорії: ${category}.
Вимоги:
- несподіваний правдивий факт без міфів;
- малознайомий широкому загалу — уникай найзатертіших шкільних фактів,
  які всі й так чули сотні разів (наприклад «мед не псується», «банан —
  це ягода», «блискавка гарячіша за Сонце»); шукай менш очевидний,
  свіжіший ракурс чи менш розкручений факт;
- обов'язково містить конкретну вражаючу цифру чи порівняння (не загальне
  твердження) — саме конкретика змушує ділитися роликом;
- факт має давати відчуття «тепер я знаю щось цікаве» — те, що самому
  захочеться переказати друзям;
- якщо органічно можливо (без натягування) — плюс, якщо факт має зв'язок
  з Україною (український винахідник, постать, місце, рекорд): такі теми
  за спостереженнями заходять цій аудиторії помітно краще за нейтральні;
- факт можна показати візуально (розріз, порівняння розмірів, процес).
ЗАБОРОНЕНІ теми (вже використані): ${usedTitles.length ? usedTitles.join('; ') : 'поки немає'}
Відповідь — лише формулювання теми одним рядком, без лапок і пояснень.`;
  const theme = await chat(prompt, { temperature: 1 });
  // На випадок, якщо модель усе ж загорнула тему в лапки.
  return theme.split('\n')[0].replace(/^["«»']+|["«»']+$/g, '').trim();
}

// Текст озвучки для відео (використовується лише коли ENABLE_TTS=1).
// Якщо власник надіслав сценарій слайдів (script) — озвучка складається
// з текстів слайдів; інакше — генерується за темою.
export async function generateNarration(theme, script) {
  const source = script
    ? `Ось сценарій слайдшоу (тексти 6 фото). Передай СУТЬ кожного слайда по
порядку, але НЕ копіюй тексти дослівно — вільно скорочуй і перефразовуй,
щоб укластися в ліміт нижче. Головне — зміст факту й порядок слайдів, а не
точні формулювання. Пункти-переліки фінального слайда (типу «неймовірні
факти / цікавий світ») НЕ озвучуй.
Якщо в тексті є номер разом із власною назвою (наприклад «16 Психе»),
сформулюй природним реченням БЕЗ граматичного відмінювання назви за
числівником (не «шістнадцятий психа», а «астероїд Психея»).
Сценарій:
${script}`
    : `Тема ролика: ${theme}
ГАЧОК: почни з найшокуючого твердження чи цифри одразу (без «Чи знали
ви…»), щоб зачепити з першої секунди. Далі 2–3 найвражаючі деталі факту
(цифри, порівняння). Останнє речення — ПЕТЛЯ: коротко чіпляє назад до
початку («а це ще не найдивніше»), заохочуючи передивитись.`;
  // Для ElevenLabs v3 текст збагачується аудіо-тегами — вони не читаються
  // вголос, а керують грою голосу (для інших рушіїв теги вирізаються в tts.js).
  const audioTags =
    process.env.TTS_ENGINE === 'elevenlabs'
      ? `
Додай 1–2 аудіо-теги у квадратних дужках англійською лише де це справді
доречно: [excited] для хука, [impressed] для вражаючої цифри. НЕ став
[whispers] і теги, що додають довгі паузи — начитка має вкластися в час.`
      : '';
  const prompt = `Ти — диктор українського TikTok-каналу «Чи Ви Знали?».
${source}
Напиши текст озвучки для відео з 6 слайдів по 4 секунди (разом 21 с).
Вимоги до синхрону (ЖОРСТКО — задовга начитка обрізається):
- НЕ більше 240 символів разом (рахуй з пробілами) і 28–34 слів — щоб
  начитка вклалася у ~18 секунд навіть із виразними інтонаціями;
- рівно одне коротке речення на кожен слайд (6 речень), у порядку слайдів
  — нову фразу починай для наступного слайда, голос має збігатися зі
  зміною кадрів кожні ~4 секунди й не забігати наперед;
- ГАЧОК: перше речення — найсильніше, без «Чи знали ви…»;
- КІНЦІВКА (не реклама): останнє речення чіпляє назад до початку й
  заохочує передивитись; слово «підписуйся» встав коротко й ненав'язливо
  в цю ж фразу, а НЕ окремим рекламним закликом із переліками.
ЯСНІСТЬ (важливо): чітко назви САМ предмет факту повним словом хоча б раз
на початку (напр. «печера», «астероїд», «риба») — глядач має зрозуміти,
про ЩО йдеться, навіть не читаючи тексту на слайдах. НЕ починай і не
завершуй займенником «вона/воно/він» без зрозумілого попередника — за
скороченням не губи головний іменник.
Жива розмовна українська. Без емодзі, без лапок, без заголовків
і нумерації — лише суцільний текст для читання вголос.
У запозичених і рідкісних словах з неочевидним наголосом познач
наголошену голосну комбінованим акутом U+0301 (наприклад: колі́брі,
жалюзі́) — це керує вимовою диктора.${audioTags}`;
  return chat(prompt, { temperature: 0.9 });
}

export async function generatePostTexts(theme) {
  const prompt = `Ти — SMM українського TikTok-каналу «Чи Ви Знали?» (пізнавальні факти).
Тема сьогоднішнього ролика: ${theme}
Згенеруй тексти для публікації. Відповідь — строго JSON:
{
  "title": "чіпляюча назва до 60 символів з 1 емодзі",
  "description": "опис за форматом нижче",
  "hashtags": "рівно 5 хештегів українською в один рядок",
  "music": "3 варіанти музики під це відео з каталогу TikTok, кожен з нового рядка у форматі: 1. Назва треку — виконавець (чому пасує, 3–5 слів). Обирай популярні/вірусні в TikTok звуки, що підходять під настрій теми: інтригуючі, епічні або атмосферні."
}

Формат description — 4 абзаци, розділені порожнім рядком, кожен з емодзі:
1. Хук: тематичне емодзі + інтригуюче питання «Чи знали ви, що …?» + 😲
2. Найвражаюча деталь факту одним-двома реченнями (з цифрою чи порівнянням, можна з емодзі).
3. Питання-залучення до глядача, наприклад «А ви знали про це? 👇»
4. Заклик: «Підписуйся, щоб не пропустити нові неймовірні факти! 🧠✨» (можна варіювати формулювання та емодзі).

Приклад description:
🍯 Чи знали ви, що мед може залишатися їстівним тисячі років? 😲

Археологи знаходили мед у єгипетських гробницях, і він не зіпсувався навіть через понад 3000 років!

А ви знали про це? 👇

Підписуйся, щоб не пропустити нові неймовірні факти! 🧠✨`;
  const raw = await chat(prompt, { response_format: { type: 'json_object' } });
  const parsed = JSON.parse(raw);
  for (const field of ['title', 'description', 'hashtags']) {
    if (typeof parsed[field] !== 'string' || !parsed[field].trim()) {
      throw new Error(`OpenAI: у відповіді немає поля «${field}»`);
    }
  }
  return {
    title: parsed.title.trim(),
    description: parsed.description.trim(),
    hashtags: parsed.hashtags.trim(),
    // Музика — допоміжна порада, без неї публікація не блокується.
    music: typeof parsed.music === 'string' && parsed.music.trim() ? parsed.music.trim() : null,
  };
}
